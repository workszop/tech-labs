// Polska odmiana po liczebniku. Lokalna kopia reguły z plural() w '@/i18n': import z '@/i18n'
// tworzyłby cykl (i18n/index -> pl -> i18n/index).
function plural(n: number, one: string, few: string, many: string): string {
  const m10 = n % 10
  const m100 = n % 100
  if (n === 1) return one
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few
  return many
}

