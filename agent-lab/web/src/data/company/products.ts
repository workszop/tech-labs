import type { Product, ProductCategory } from './types'

function p(
  id: string,
  model: string,
  category: ProductCategory,
  serialPrefix: string | null,
  warrantyMonths: 12 | 24 | 36,
  priceEur: number,
  launchYear: number,
  discontinued: string | null,
  en: string,
  pl: string,
): Product {
  return {
    id,
    model,
    category,
    kind: serialPrefix ? 'appliance' : 'accessory',
    serialPrefix,
    warrantyMonths,
    priceEur,
    launchYear,
    inProduction: discontinued === null,
    discontinued,
    description: { en, pl },
  }
}

